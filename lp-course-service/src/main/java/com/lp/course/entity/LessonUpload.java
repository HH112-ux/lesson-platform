package com.lp.course.entity;

import java.time.LocalDateTime;

/**
 * One presigned upload session stored in {@code lesson_upload}.
 *
 * <p>A row is created before the client starts uploading and carries the object key the client must
 * put its video to. {@link #status} starts as {@code 0} and is only moved to {@code 1} after the
 * server confirms the object with {@code statObject}. The table keeps the generated {@code
 * pending_flag} column outside this model: it exists only to build the {@code uk_lesson_pending}
 * unique key and must never be written by the application.
 *
 * @author Caspian
 * @since 0.7.0
 */
public class LessonUpload {

    private Long id;

    private Long courseId;

    private Long chapterId;

    private Long lessonId;

    private Long uploaderId;

    private String objectKey;

    private String contentType;

    private Long expectedSizeBytes;

    private Integer status;

    private LocalDateTime sessionExpiresAt;

    private LocalDateTime confirmedAt;

    private LocalDateTime createdAt;

    private LocalDateTime updatedAt;

    /**
     * Returns the session id.
     *
     * @return primary key
     * @author Caspian
     * @since 0.7.0
     */
    public Long getId() {
        return id;
    }

    /**
     * Sets the session id.
     *
     * @param id primary key
     * @author Caspian
     * @since 0.7.0
     */
    public void setId(Long id) {
        this.id = id;
    }

    /**
     * Returns the owning course id.
     *
     * @return {@code course.id}
     * @author Caspian
     * @since 0.7.0
     */
    public Long getCourseId() {
        return courseId;
    }

    /**
     * Sets the owning course id.
     *
     * @param courseId {@code course.id}
     * @author Caspian
     * @since 0.7.0
     */
    public void setCourseId(Long courseId) {
        this.courseId = courseId;
    }

    /**
     * Returns the chapter id.
     *
     * @return {@code course_chapter.id}
     * @author Caspian
     * @since 0.7.0
     */
    public Long getChapterId() {
        return chapterId;
    }

    /**
     * Sets the chapter id.
     *
     * @param chapterId {@code course_chapter.id}
     * @author Caspian
     * @since 0.7.0
     */
    public void setChapterId(Long chapterId) {
        this.chapterId = chapterId;
    }

    /**
     * Returns the lesson id the session uploads to.
     *
     * @return {@code course_lesson.id}
     * @author Caspian
     * @since 0.7.0
     */
    public Long getLessonId() {
        return lessonId;
    }

    /**
     * Sets the lesson id the session uploads to.
     *
     * @param lessonId {@code course_lesson.id}
     * @author Caspian
     * @since 0.7.0
     */
    public void setLessonId(Long lessonId) {
        this.lessonId = lessonId;
    }

    /**
     * Returns the teacher user id that started the upload.
     *
     * @return uploader user id, checked against the lesson owner on confirmation
     * @author Caspian
     * @since 0.7.0
     */
    public Long getUploaderId() {
        return uploaderId;
    }

    /**
     * Sets the teacher user id that started the upload.
     *
     * @param uploaderId uploader user id
     * @author Caspian
     * @since 0.7.0
     */
    public void setUploaderId(Long uploaderId) {
        this.uploaderId = uploaderId;
    }

    /**
     * Returns the storage object key the client uploads to.
     *
     * @return object key, never a public URL
     * @author Caspian
     * @since 0.7.0
     */
    public String getObjectKey() {
        return objectKey;
    }

    /**
     * Sets the storage object key.
     *
     * @param objectKey object key generated by the server
     * @author Caspian
     * @since 0.7.0
     */
    public void setObjectKey(String objectKey) {
        this.objectKey = objectKey;
    }

    /**
     * Returns the declared content type.
     *
     * @return declared content type, {@code video/mp4} for the current upload path
     * @author Caspian
     * @since 0.7.0
     */
    public String getContentType() {
        return contentType;
    }

    /**
     * Sets the declared content type.
     *
     * @param contentType declared content type
     * @author Caspian
     * @since 0.7.0
     */
    public void setContentType(String contentType) {
        this.contentType = contentType;
    }

    /**
     * Returns the declared file size.
     *
     * @return declared size in bytes, at most 209715200
     * @author Caspian
     * @since 0.7.0
     */
    public Long getExpectedSizeBytes() {
        return expectedSizeBytes;
    }

    /**
     * Sets the declared file size.
     *
     * @param expectedSizeBytes declared size in bytes
     * @author Caspian
     * @since 0.7.0
     */
    public void setExpectedSizeBytes(Long expectedSizeBytes) {
        this.expectedSizeBytes = expectedSizeBytes;
    }

    /**
     * Returns the session status.
     *
     * @return 0 pending, 1 confirmed, 2 expired, 3 aborted, see {@code LessonUploadStatus}
     * @author Caspian
     * @since 0.7.0
     */
    public Integer getStatus() {
        return status;
    }

    /**
     * Sets the session status.
     *
     * @param status 0 pending, 1 confirmed, 2 expired, 3 aborted
     * @author Caspian
     * @since 0.7.0
     */
    public void setStatus(Integer status) {
        this.status = status;
    }

    /**
     * Returns the expiry of the presigned upload credential.
     *
     * @return expiration time, issued at creation plus 30 minutes
     * @author Caspian
     * @since 0.7.0
     */
    public LocalDateTime getSessionExpiresAt() {
        return sessionExpiresAt;
    }

    /**
     * Sets the expiry of the presigned upload credential.
     *
     * @param sessionExpiresAt expiration time
     * @author Caspian
     * @since 0.7.0
     */
    public void setSessionExpiresAt(LocalDateTime sessionExpiresAt) {
        this.sessionExpiresAt = sessionExpiresAt;
    }

    /**
     * Returns the time the stored object was confirmed.
     *
     * @return confirmation time, {@code null} while the session is pending
     * @author Caspian
     * @since 0.7.0
     */
    public LocalDateTime getConfirmedAt() {
        return confirmedAt;
    }

    /**
     * Sets the time the stored object was confirmed.
     *
     * @param confirmedAt confirmation time
     * @author Caspian
     * @since 0.7.0
     */
    public void setConfirmedAt(LocalDateTime confirmedAt) {
        this.confirmedAt = confirmedAt;
    }

    /**
     * Returns the creation time.
     *
     * @return creation time
     * @author Caspian
     * @since 0.7.0
     */
    public LocalDateTime getCreatedAt() {
        return createdAt;
    }

    /**
     * Sets the creation time.
     *
     * @param createdAt creation time
     * @author Caspian
     * @since 0.7.0
     */
    public void setCreatedAt(LocalDateTime createdAt) {
        this.createdAt = createdAt;
    }

    /**
     * Returns the last update time.
     *
     * @return update time
     * @author Caspian
     * @since 0.7.0
     */
    public LocalDateTime getUpdatedAt() {
        return updatedAt;
    }

    /**
     * Sets the last update time.
     *
     * @param updatedAt update time
     * @author Caspian
     * @since 0.7.0
     */
    public void setUpdatedAt(LocalDateTime updatedAt) {
        this.updatedAt = updatedAt;
    }
}
